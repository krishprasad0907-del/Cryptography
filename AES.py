# Round Constants
RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]

# Galois Field multiplication GF(2^8) helpers
def xtime(a):
    return ((a << 1) ^ 0x1B) & 0xFF if (a & 0x80) else (a << 1) & 0xFF

def gf_mult(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi_bit = a & 0x80
        a = (a << 1) & 0xFF
        if hi_bit:
            a ^= 0x1B
        b >>= 1
    return p

# --- AES ENGINE ---

class AES128:
    def __init__(self, key: bytes):
        if len(key) != 16:
            raise ValueError("AES-128 key must be exactly 16 bytes long.")
        self.key = key
        self.round_keys = self._expand_key(key)

    def _expand_key(self, key: bytes) -> list:
        """Expands 16-byte key into 11 round keys (44 words of 4 bytes)."""
        words = list(struct_unpack_words(key))
        for i in range(4, 44):
            temp = words[i - 1]
            if i % 4 == 0:
                # RotWord
                temp = ((temp << 8) & 0xFFFFFFFF) | (temp >> 24)
                # SubWord
                temp = (S_BOX[(temp >> 24) & 0xFF] << 24) | \
                       (S_BOX[(temp >> 16) & 0xFF] << 16) | \
                       (S_BOX[(temp >> 8) & 0xFF] << 8) | \
                       (S_BOX[temp & 0xFF])
                # XOR Rcon
                temp ^= (RCON[i // 4] << 24)
            words.append(words[i - 4] ^ temp)

        # Convert back to 16-byte key matrices
        round_keys = []
        for r in range(11):
            matrix = [[0] * 4 for _ in range(4)]
            for col in range(4):
                word = words[r * 4 + col]
                for row in range(4):
                    matrix[row][col] = (word >> (24 - 8 * row)) & 0xFF
            round_keys.append(matrix)
        return round_keys

    def _add_round_key(self, state, round_key):
        for r in range(4):
            for c in range(4):
                state[r][c] ^= round_key[r][c]

    def _sub_bytes(self, state, inv=False):
        box = INV_S_BOX if inv else S_BOX
        for r in range(4):
            for c in range(4):
                state[r][c] = box[state[r][c]]

    def _shift_rows(self, state, inv=False):
        for r in range(1, 4):
            shift = -r if inv else r
            state[r] = state[r][shift:] + state[r][:shift]

    def _mix_columns(self, state, inv=False):
        for c in range(4):
            s0, s1, s2, s3 = state[0][c], state[1][c], state[2][c], state[3][c]
            if not inv:
                state[0][c] = xtime(s0) ^ (xtime(s1) ^ s1) ^ s2 ^ s3
                state[1][c] = s0 ^ xtime(s1) ^ (xtime(s2) ^ s2) ^ s3
                state[2][c] = s0 ^ s1 ^ xtime(s2) ^ (xtime(s3) ^ s3)
                state[3][c] = (xtime(s0) ^ s0) ^ s1 ^ s2 ^ xtime(s3)
            else:
                state[0][c] = gf_mult(s0, 0x0e) ^ gf_mult(s1, 0x0b) ^ gf_mult(s2, 0x0d) ^ gf_mult(s3, 0x09)
                state[1][c] = gf_mult(s0, 0x09) ^ gf_mult(s1, 0x0e) ^ gf_mult(s2, 0x0b) ^ gf_mult(s3, 0x0d)
                state[2][c] = gf_mult(s0, 0x0d) ^ gf_mult(s1, 0x09) ^ gf_mult(s2, 0x0e) ^ gf_mult(s3, 0x0b)
                state[3][c] = gf_mult(s0, 0x0b) ^ gf_mult(s1, 0x0d) ^ gf_mult(s2, 0x09) ^ gf_mult(s3, 0x0e)

    def encrypt_block(self, block: bytes) -> bytes:
        state = [[block[r + 4 * c] for c in range(4)] for r in range(4)]

        self._add_round_key(state, self.round_keys[0])

        for round_idx in range(1, 10):
            self._sub_bytes(state)
            self._shift_rows(state)
            self._mix_columns(state)
            self._add_round_key(state, self.round_keys[round_idx])

        # Final Round (No MixColumns)
        self._sub_bytes(state)
        self._shift_rows(state)
        self._add_round_key(state, self.round_keys[10])

        return bytes(state[r][c] for c in range(4) for r in range(4))

    def decrypt_block(self, block: bytes) -> bytes:
        state = [[block[r + 4 * c] for c in range(4)] for r in range(4)]

        self._add_round_key(state, self.round_keys[10])

        for round_idx in range(9, 0, -1):
            self._shift_rows(state, inv=True)
            self._sub_bytes(state, inv=True)
            self._add_round_key(state, self.round_keys[round_idx])
            self._mix_columns(state, inv=True)

        # Final Round
        self._shift_rows(state, inv=True)
        self._sub_bytes(state, inv=True)
        self._add_round_key(state, self.round_keys[0])

        return bytes(state[r][c] for c in range(4) for r in range(4))

    def encrypt_bytes(self, text_bytes: bytes) -> bytes:
        pad_len = 16 - (len(text_bytes) % 16)
        padded = text_bytes + bytes([pad_len] * pad_len)
        out = bytearray()
        for i in range(0, len(padded), 16):
            out.extend(self.encrypt_block(padded[i:i+16]))
        return bytes(out)

    def decrypt_bytes(self, cipher_bytes: bytes) -> bytes:
        if len(cipher_bytes) % 16 != 0:
            raise ValueError("Ciphertext length must be a multiple of 16 bytes.")
        out = bytearray()
        for i in range(0, len(cipher_bytes), 16):
            out.extend(self.decrypt_block(cipher_bytes[i:i+16]))
        pad_len = out[-1]
        if pad_len < 1 or pad_len > 16:
            raise ValueError("Invalid padding detected or incorrect key.")
        return bytes(out[:-pad_len])

def struct_unpack_words(data: bytes):
    for i in range(0, len(data), 4):
        yield (data[i] << 24) | (data[i+1] << 16) | (data[i+2] << 8) | data[i+3]


# --- INTERACTIVE CLI ---

def get_valid_key():
    while True:
        key_input = input("\nEnter 16-character AES-128 key: ").strip()
        key_bytes = key_input.encode('utf-8')
        if len(key_bytes) == 16:
            return key_bytes
        print(f"Error: Key must be exactly 16 bytes (yours was {len(key_bytes)}).")

def main():
    print("=" * 60)
    print("AES-128 (RIJNDAEL) ENCRYPTION / DECRYPTION TOOL")
    print("=" * 60)

    key_bytes = get_valid_key()
    cipher = AES128(key_bytes)

    while True:
        print("\n--- MENU ---")
        print("1. Encrypt Plaintext")
        print("2. Decrypt Hex Ciphertext")
        print("3. Change Key")
        print("4. Exit")

        choice = input("\nSelect Option (1-4): ").strip()

        if choice == "1":
            text = input("\nEnter message to encrypt: ")
            encrypted = cipher.encrypt_bytes(text.encode('utf-8'))
            print(f"\nCiphertext (Hex): {encrypted.hex()}")

        elif choice == "2":
            hex_str = input("\nEnter Hex ciphertext to decrypt: ").strip()
            try:
                cipher_bytes = bytes.fromhex(hex_str)
                decrypted = cipher.decrypt_bytes(cipher_bytes).decode('utf-8')
                print(f"\nDecrypted Message: {decrypted}")
            except ValueError as ve:
                print(f"\nDecryption Failed: {ve}")
            except Exception as e:
                print(f"\nError: Could not decode ciphertext ({e}).")

        elif choice == "3":
            key_bytes = get_valid_key()
            cipher = AES128(key_bytes)
            print("Key updated successfully.")

        elif choice == "4":
            print("Exiting.")
            break
        else:
            print("Invalid option. Enter 1, 2, 3, or 4.")

if __name__ == "__main__":
    main()